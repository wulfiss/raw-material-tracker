import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { resolve } from 'node:path';

const root = fileURLToPath(new URL('../', import.meta.url));
const sources = [['Products cocina.txt', 'Cocina'], ['Fiambreria.txt', 'Fiambrería']];
export function parseSource(text, source, category) {
  let intermediate = false;
  const records = [];
  for (const line of text.split(/\r?\n/)) {
    if (/^2\. Recetas/.test(line)) intermediate = true;
    const match = line.match(/^(\d+)\t([^\t]+)\t(.+)$/);
    if (!match) continue;
    const [, number, name, details] = match;
    const membershipOnly = category === 'Fiambrería' && intermediate;
    records.push({ key: `${category}:${number}:${intermediate ? 'intermediate' : 'final'}`, name: name.trim(), category,
      intermediate, source, sourceRow: Number(number), sourceDetails: details.trim(),
      ingredients: membershipOnly ? [] : details.replace(/\.\s*$/, '').split(',').map(s => s.trim()).filter(Boolean) });
  }
  return records;
}
const quote = value => "'" + value.replaceAll("'", "''") + "'";
export function buildImport() {
  const records = sources.flatMap(([source, category]) => parseSource(readFileSync(resolve(root, 'data/recipes', source), 'utf8'), source, category));
  const rawMaterials = records.filter(r => r.category === 'Fiambrería' && r.intermediate);
  const recipes = records.filter(r => !rawMaterials.includes(r));
  const rawAliases = {
    'Relleno de jamón y queso': 'Relleno de jamón y queso',
    'Salsa de tomate': 'Salsa de tomate',
    'Prepizza': 'Prepizza',
    'salsa': 'Salsa (sin especificar)',
    'milanesa de carne vacuna cocida y refrigerada': 'Milanesa de carne vacuna cocida',
    'milanesa de pollo cocida y refrigerada': 'Milanesa de pollo cocida',
  };
  // Only explicit preparation equivalences. Keep brands, food states, alternatives,
  // and ambiguous names from the documents instead of guessing raw-material aliases.
  const links = {
    'Relleno de acelga preparado': 'Cocina:1:intermediate',
    'Relleno de atún preparado': 'Cocina:4:intermediate',
    'Salsa boloñesa': 'Cocina:5:intermediate',
    'Papa hervida': 'Cocina:31:final',
    'zanahoria hervida en cubos': 'Cocina:35:final',
    'Zanahoria hervida en cubos': 'Cocina:35:final',
  };
  const keys = new Set(recipes.map(r => r.key));
  for (const r of recipes) r.ingredients = [...new Set(r.ingredients)].map(name => {
    const target = links[name];
    const rawMaterial = Object.entries(rawAliases).find(([alias]) => alias.toLocaleLowerCase('es') === name.toLocaleLowerCase('es'))?.[1];
    if (target && !keys.has(target)) throw new Error(`Missing preparation ${target}`);
    if (target === r.key) throw new Error(`Self reference ${r.key}`);
    return { name, preparation: target ?? null, ...(rawMaterial ? { rawMaterial } : {}) };
  });
  const json = JSON.stringify(recipes, null, 2);
  const sql = `-- Generated by node scripts/build-recipe-import.mjs from data/recipes/*.txt.
-- Transactional and repeatable. Converts the six old empty imported placeholders
-- to raw materials if the previous version of this import was applied.
-- Source documents contain membership only: legacy quantity/yield values of 1
-- are compatibility placeholders, NOT measured quantities or stock instructions.
begin;
alter table public.recipes add column if not exists import_key text;
create unique index if not exists recipes_import_key_idx on public.recipes(import_key) where import_key is not null;
alter table public.recipes add column if not exists output_material_id uuid references public.materials(id);
alter table public.recipes add column if not exists quantities_specified boolean not null default true;
create index if not exists recipes_output_material_idx on public.recipes(output_material_id);
do $import$
declare
  doc jsonb := ${quote(json)}::jsonb;
  raw_doc jsonb := ${quote(JSON.stringify(rawMaterials))}::jsonb;
  item jsonb;
  ingredient jsonb;
  recipe_uuid uuid;
  material_uuid uuid;
  material_label text;
  ingredient_order integer;
begin
  -- These six source entries are purchased/raw inputs, not recipe definitions.
  for item in select value from jsonb_array_elements(raw_doc) loop
    insert into public.materials(name, category, unit, storage_condition, expiration_required)
      values (item->>'name', 'Materias primas', 'unit', 'ambient', false)
      on conflict (name) do nothing;
  end loop;
  -- Create all outputs first, including final products that can be ingredients.
  for item in select value from jsonb_array_elements(doc) loop
    material_label := (item->>'name') || ' [' || (item->>'category') || ' · elaborado]';
    insert into public.materials(name, category, unit, storage_condition, expiration_required)
      values (material_label, 'Elaborados / ' || (item->>'category'), 'unit', 'ambient', false)
      on conflict (name) do nothing;
    select id into strict material_uuid from public.materials where name = material_label;
    insert into public.recipes(name, category, yield_quantity, yield_unit, active, notes, import_key, output_material_id, quantities_specified)
      values (item->>'name', (item->>'category') || case when (item->>'intermediate')::boolean then ' / Intermedio' else ' / Terminado' end,
        1, 'unit', jsonb_array_length(item->'ingredients') > 0,
        'Fuente: ' || (item->>'source') || ', fila ' || (item->>'sourceRow') || '. Cantidades y rendimiento no especificados; valores 1 solo por compatibilidad. Conservación y unidad de materiales nuevos pendientes de revisión. Detalle original: ' || (item->>'sourceDetails'),
        'catalogue-v1:' || (item->>'key'), material_uuid, false)
      on conflict (import_key) where import_key is not null do nothing;
  end loop;
  for item in select value from jsonb_array_elements(doc) loop
    select id into strict recipe_uuid from public.recipes where import_key = 'catalogue-v1:' || (item->>'key');
    ingredient_order := 0;
    for ingredient in select value from jsonb_array_elements(item->'ingredients') loop
      if ingredient->>'preparation' is not null then
        select output_material_id into strict material_uuid from public.recipes
          where import_key = 'catalogue-v1:' || (ingredient->>'preparation');
      else
        material_label := coalesce(ingredient->>'rawMaterial', ingredient->>'name');
        insert into public.materials(name, category, unit, storage_condition, expiration_required)
          values (material_label, 'Importado / Revisar', 'unit', 'ambient', false)
          on conflict (name) do nothing;
        select id into strict material_uuid from public.materials where name = material_label;
      end if;
      -- Repoint memberships from the previous import, retaining source notes.
      if ingredient->>'rawMaterial' is not null then
        update public.recipe_ingredients set material_id = material_uuid
          where recipe_id = recipe_uuid
          and notes = 'Cantidad no especificada. Nombre original: ' || (ingredient->>'name')
          and material_id <> material_uuid
          and not exists (select 1 from public.recipe_ingredients current_ingredient
            where current_ingredient.recipe_id = recipe_uuid and current_ingredient.material_id = material_uuid);
      end if;
      insert into public.recipe_ingredients(recipe_id, material_id, quantity, unit, notes, sort_order)
        select recipe_uuid, material_uuid, 1, unit,
          'Cantidad no especificada. Nombre original: ' || (ingredient->>'name'), ingredient_order
        from public.materials where id = material_uuid
        on conflict (recipe_id, material_id) do nothing;
      ingredient_order := ingredient_order + 1;
    end loop;
  end loop;
  -- Remove only untouched, empty placeholders made by the previous import.
  -- Foreign keys protect any placeholder referenced by operational records.
  delete from public.recipes r using jsonb_array_elements(raw_doc) raw
    where r.import_key = 'catalogue-v1:' || (raw->>'key')
      and not r.active and not r.quantities_specified
      and not exists (select 1 from public.recipe_ingredients i where i.recipe_id = r.id)
      and not exists (select 1 from public.recipe_ingredients i where i.material_id = r.output_material_id);
end $import$;
commit;
`;
  return { recipes, rawMaterials, sql };
}
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const { recipes, rawMaterials, sql } = buildImport();
  writeFileSync(resolve(root, 'supabase/import-product-recipes.sql'), sql);
  console.log(JSON.stringify({ recipes: recipes.length, ingredients: recipes.reduce((n,r) => n+r.ingredients.length,0), rawMaterials: rawMaterials.length }));
}
